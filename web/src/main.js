import { createDefaultStudy } from './core/defaultStudy.js';
import { createStore } from './core/store.js';
import { createRouter } from './core/router.js';
import { renderShell } from './ui/shell.js';
import { clearAll, loadMostRecentRecoverable, saveExperiment } from './core/persist.js';
import { shapeAppKb } from './engine/kbpack.js';
import { namingStep } from './ui/steps/naming.js';
import { createDescribeStep } from './ui/steps/describe.js';
import { designStep } from './ui/steps/design.js';
import { studyStep } from './ui/steps/study.js';
import { createOverviewStep } from './ui/steps/overview.js';

const AUTOSAVE_DEBOUNCE_MS = 500;

/**
 * Read the knowledge pack from the ONE place its global is read, then hand
 * it to shapeAppKb (engine/kbpack.js) for the actual shaping -- that part is
 * a pure function and is what's under test; this wrapper is the one line
 * that is allowed to touch globalThis.
 *
 * globalThis.__MICRONAUT_KB__ is embedded by tools/build_single_file.py
 * (release) or web/kb.dev.js (dev, generated by tools/export_markers_kb.py)
 * -- both aggregate web/kb/*.json by filename stem. TOTAL: an absent/
 * malformed KB degrades to "no markers known, no questions, no advice"
 * (surfaced via the shell's toast), never a white screen.
 */
function loadAppKb() {
  const rawKb = typeof globalThis !== 'undefined' ? globalThis.__MICRONAUT_KB__ : undefined;
  return shapeAppKb(rawKb);
}

/**
 * The thin wrapper around core/persist.js's loadMostRecentRecoverable that
 * supplies main.js's own console.error logging and the createDefaultStudy()
 * fallback -- persist.js deliberately doesn't know what a fresh study looks
 * like, so `experiment: null` means "start fresh" here. Only fires when
 * NO usable autosave exists at all (true first run, or every ring slot was
 * corrupted) -- an existing in-progress study is never touched.
 */
function loadInitialExperiment() {
  const { experiment, skippedCount, totalSaved } = loadMostRecentRecoverable({
    onUnreadable: (id, err) =>
      console.error(`Discarding an unreadable autosave (slot ${id}), trying the next one:`, err),
  });
  return { experiment: experiment || createDefaultStudy(), skippedCount, totalSaved };
}

// Bootstrap, not top-level await -- the single-file inliner forbids
// top-level await since the released artifact is one classic (non-module,
// non-async) IIFE.
function init() {
  const { experiment: initialExperiment, skippedCount, totalSaved } = loadInitialExperiment();
  const store = createStore(initialExperiment);

  const kb = loadAppKb();
  const describeStep = createDescribeStep(kb);
  const overviewStep = createOverviewStep(kb);
  // Study first: it is the study-level surface sitting above every assay,
  // and the discoverability point for "this app can model more than one
  // assay" -- the router lands on steps[0] by default, so this is also the
  // new landing step. See docs/plans/planner-web-assay-tier.md, commit 2.
  // Overview last: it is a pure READ over every other step's data (the
  // shareable diagram + deterministic walkthrough), never a place new facts
  // are entered -- see ui/steps/overview.js's module header.
  const steps = [studyStep, describeStep, designStep, namingStep, overviewStep];
  const router = createRouter(steps);

  const root = document.getElementById('app');
  const { main, showToast } = renderShell(root, store, router, {
    // Clear persisted state BEFORE reloading. Resetting the in-memory store
    // instead would immediately trip the autosave subscription below and write
    // the empty experiment back as a NEW ring entry, leaving the old slots in
    // place for listSaved() to resurrect on the next load.
    onReset: () => {
      clearAll();
      window.location.reload();
    },
  });

  if (kb.issues.length > 0) {
    showToast(
      `Knowledge pack loaded with ${kb.issues.length} issue(s) -- some markers or guidance may be unavailable.`
    );
  }

  // Shown AFTER the KB toast (shell.js's showToast is a single status
  // element, not a queue -- the later call wins the visible window), since
  // a possible-data-loss message is rarer and more consequential than a
  // KB-content issue.
  if (skippedCount > 0) {
    showToast(
      skippedCount < totalSaved
        ? `Recovered your work -- skipped ${skippedCount} unreadable autosave(s) and used an older one instead.`
        : `Couldn't read any of your ${totalSaved} saved experiment(s) -- starting fresh. Nothing was deleted.`
    );
  }

  function renderActiveStep(id) {
    const step = steps.find((s) => s.id === id) || steps[0];
    step.render(main, store, { showToast, advisor: kb.advisor, router });
  }

  router.onChange(renderActiveStep);
  renderActiveStep(router.current());

  // Every step's render() caches activeAssayId ONCE and documents that this
  // is only safe because the active assay never changes for the lifetime of
  // one render (see e.g. design.js's identical comment). The assay switcher
  // (shell.js) now makes that untrue, so switching assays must force a full
  // re-render of whichever step is on screen -- same as a route change,
  // because every closure inside render() (currentDesign(), prefill, etc.)
  // was built from the OLD assayId. Guarded on an actual change so ordinary
  // per-keystroke field edits (which also flow through this same
  // store.subscribe channel via the autosave one below) never trigger it.
  let lastActiveAssayId = store.get().activeAssayId;
  store.subscribe((state) => {
    if (state.activeAssayId !== lastActiveAssayId) {
      lastActiveAssayId = state.activeAssayId;
      renderActiveStep(router.current());
    }
  });

  // Debounced: saving on every keystroke would fill the 5-slot ring buffer
  // with near-duplicate snapshots of the last few characters typed, rather
  // than the last 5 genuinely distinct states the ring buffer exists to
  // preserve as history.
  let saveTimer = null;
  store.subscribe(() => {
    if (saveTimer) window.clearTimeout(saveTimer);
    saveTimer = window.setTimeout(() => {
      saveExperiment(store.get(), {
        onQuotaExceeded: () => {
          showToast('Storage is full -- changes are not being saved automatically. Export to a file.');
        },
      });
    }, AUTOSAVE_DEBOUNCE_MS);
  });
}

init();
