/**
 * Read the knowledge pack from the ONE place its global is read, then hand
 * it to shapeAppKb (engine/kbpack.js) for the actual shaping -- that part is
 * a pure function and is what's under test; this wrapper is the one line
 * that is allowed to touch globalThis.
 *
 * globalThis.__MICRONAUT_KB__ is embedded by tools/build_single_file.py
 * (release) or web/kb.dev.js (dev, generated by tools/serve_dir.py) --
 * both aggregate web/kb/*.json by filename stem. TOTAL: an absent/
 * malformed KB degrades to "no markers known, no questions, no advice"
 * (surfaced via the shell's toast), never a white screen.
 */
function loadAppKb() {
  const rawKb = typeof globalThis !== 'undefined' ? globalThis.__MICRONAUT_KB__ : undefined;
  return shapeAppKb(rawKb);
}

// A first run starts BLANK, not on the shipped oregano example. Seeding the
// example made a visitor's first workspace someone else's four-measurement
// study, and an entire ownership subsystem (banners, read-only exploration,
// "make a copy") existed only to walk that back. The example is still one
// click away -- see openExampleStudy() (core/appController.js) and Home's
// "Open the example study" -- but it is now something the visitor asks for
// rather than something they have to disown.

// Bootstrap, not top-level await -- the single-file inliner forbids
// top-level await since the released artifact is one classic (non-module,
// non-async) IIFE.
function init() {
  // The persist.js bundle handed to appController -- explicit rather than
  // importing core/persist.js directly inside appController.js, so a test
  // can supply an in-memory fake for every one of these without touching
  // localStorage.
  const persistBundle = {
    clearAll,
    deleteExperiment,
    exportToFile,
    importFromFile,
    listSaved,
    loadExperiment,
    loadMostRecentRecoverable,
    loadRecoverableSlot,
    markChanged,
    markExported,
    saveExperiment,
  };

  const { experiment: initialExperiment, skippedCount, totalSaved, isPersisted } = resolveInitialExperiment(
    persistBundle,
    emptyExperiment,
    {
      onUnreadable: (id, err) =>
        console.error(`Discarding an unreadable autosave (slot ${id}), trying the next one:`, err),
    }
  );
  const store = createStore(initialExperiment);

  // The guidedProgress.js bundle handed to appController, same reasoning as
  // persistBundle above.
  const guidedBundle = {
    load: loadGuidedProgress,
    start: startGuidedProgress,
    resume: resumeGuidedProgress,
    pause: pauseGuidedProgress,
    advance: advanceGuidedProgress,
    restart: restartGuidedProgress,
  };

  // The lifecycle coordinator: every closure that touches store+persist
  // (recovery ring, project import/export, guided-progress transitions, the
  // debounced autosave subscriber) lives in core/appController.js now, not
  // here -- see that module's header comment for why.
  const appController = createAppController({
    store,
    persist: persistBundle,
    guided: guidedBundle,
    primaryWorkflow: PRIMARY_WORKFLOW,
    createExampleStudy: createDefaultStudy,
    createEmptyStudy: emptyExperiment,
    isPersisted,
  });

  const kb = loadAppKb();
  const describeStep = createDescribeStep(kb);
  const panelStep = createPanelStep(kb);
  const overviewStep = createOverviewStep(kb);
  const namingStep = createNamingStep(kb);
  // The nav names things a study HAS, not steps to march through:
  //
  //   Study map     the shape of the study -- question, system, comparison, unit
  //   Research brief the narrative and what the exact-text scan found in it
  //   Measurements  the registry: every measurement, searchable and filterable
  //   Measurement   the one you opened: samples & design + acquisition + data plan
  //   Review        a read over everything, plus every export
  //
  // Samples & design, Acquisition and Data plan are no longer routes. They are
  // sections of the measurement page, composed by createMeasurementStep from
  // the very same step objects -- which is why designStep/panelStep/namingStep
  // are still constructed here and handed to it rather than being rewritten.
  // Old #/design, #/panel and #/naming links still resolve; see
  // core/router.js's ROUTE_ALIASES.
  //
  // Guide, Feedback and Settings stay reachable but sit outside the workflow:
  // they are utilities, and counting them as planning stages was part of what
  // made the nav read as an exam.
  const measurementStep = createMeasurementStep({ panelStep, namingStep });
  const steps = [homeStep, describeStep, studyStep, measurementStep, overviewStep, guideStep, feedbackStep, settingsStep];
  const router = createRouter(steps);

  const root = document.getElementById('app');
  let shell = null;

  // One exact producer chain for the shell: use the same shaped KB and
  // naming constants as Overview, derive conformance once, then hand that
  // report unchanged to workflow progress. The shell only consumes this
  // model; it never reclassifies placeholders or warning severities.
  function currentWorkflowProgress() {
    const experiment = store.get();
    const conformance = checkConformance(experiment, kb, NAMING_CONFIG, BASE_TEMPLATE);
    return deriveWorkflowProgress(experiment, conformance, kb.questions);
  }

  // The guided walkthrough and the router now share one vocabulary: the
  // walkthrough's per-measurement stop IS the measurement route. The old
  // microscopy<->panel translation is gone with the panel route.
  function guidedRouteIdForStep(stepId) {
    return stepId;
  }

  function guidedStepIdForRoute(routeId) {
    return routeId;
  }

  let guidedController = null;
  let featureWalkthroughController = null;

  shell = renderShell(root, store, router, {
    kbIssueCount: kb.issues.length,
    saveState: appController.getSaveState(),
    recoveryEntries: appController.recoveryEntries(),
    workflowProgress: currentWorkflowProgress(),
    // appController.actions carries every lifecycle callback the shell's
    // buttons need (onReset/onNewBlank/onAdoptExample/onOpenExample/
    // onExportProject/onImportProject/onRestoreRecovery/onDeleteRecovery/
    // onClearAllStorage) -- the same object is spread into renderActiveStep's
    // step options below, so both consumers share one set of callbacks.
    ...appController.actions,
  });
  // Explicit second phase, same two-phase pattern the pre-extraction code
  // used (showToast was destructured from shell only after the callbacks
  // above were already handed to renderShell): appController's callbacks are
  // built and handed to renderShell before the shell they call back into
  // exists at all.
  appController.attachShell(shell);
  const { main, showToast } = shell;

  // Main is the sole lifecycle coordinator: the shell supplies one stable
  // host, while this controller receives the canonical workflow, fresh
  // projections, routing aliases, durable transitions, and lifecycle
  // callbacks exactly once after renderShell has created the host.
  guidedController = createWalkthroughController({
    host: shell.guidedAsideHost,
    primaryWorkflow: PRIMARY_WORKFLOW,
    router,
    getContent: () => buildGuidedExampleContent(store.get(), {
      primaryWorkflow: PRIMARY_WORKFLOW,
      kb,
      namingConfig: NAMING_CONFIG,
      baseTemplate: BASE_TEMPLATE,
    }),
    getProgress: () => appController.getGuidedState(),
    transitions: appController.guidedTransitions,
    routeForStep: guidedRouteIdForStep,
    stepForRoute: guidedStepIdForRoute,
    subscribe: (listener) => store.subscribe(listener),
    onAdoptExample: appController.actions.onAdoptExample,
    onNewBlank: appController.actions.onNewBlank,
    onKeepExploringExample: () => {},
    onExportProject: appController.actions.onExportProject,
    onVisibilityChange: shell.setGuidedAsideVisible,
  });
  shell.setExplainStepHandler((stepId) => guidedController.explain(stepId));
  // The feature tour is available ONLY from the header's Walkthrough button.
  // It used to launch itself on a first visit and again on any return after
  // 24h away, so a returning user opening a new tab was met by a multi-stop
  // product tour they never asked for. Guidance that starts itself is the
  // thing that made five explanatory surfaces feel like five interruptions.
  featureWalkthroughController = createFeatureWalkthroughController({ router });
  shell.setFeatureWalkthroughHandler((trigger) => featureWalkthroughController.start(trigger));

  function explainGuided(stepId) {
    const routeStepId = guidedStepIdForRoute(router.current());
    const requestedStepId = PRIMARY_WORKFLOW.some((step) => step.id === stepId)
      ? stepId
      : PRIMARY_WORKFLOW.some((step) => step.id === routeStepId)
        ? routeStepId
        : PRIMARY_WORKFLOW[0]?.id;
    guidedController.explain(requestedStepId);
  }

  if (kb.issues.length > 0) {
    showToast(
      `Knowledge pack loaded with ${kb.issues.length} issue(s) -- some markers or guidance may be unavailable.`
    );
  }

  // Shown AFTER the KB toast (shell.js's showToast is a single status
  // element, not a queue -- the later call wins the visible window), since
  // a possible-data-loss message is rarer and more consequential than a
  // KB-content issue.
  if (skippedCount > 0) {
    showToast(
      skippedCount < totalSaved
        ? `Recovered your work -- skipped ${skippedCount} unreadable autosave(s) and used an older one instead.`
        : `Couldn't read any of your ${totalSaved} saved experiment(s) -- starting fresh. Nothing was deleted.`
    );
  }

  function renderActiveStep(id) {
    const step = steps.find((s) => s.id === id) || steps[0];
    // Read fresh on every render rather than caching loadOnboarding() once:
    // the onboarding gate (idea path) can complete AFTER this closure is
    // built but before the first render, and a later screen may still
    // change the stored experience level -- see docs/cma-lessons.md
    // lesson 46 (re-fetch current state inside handlers, not a stale
    // closure).
    step.render(main, store, {
      showToast,
      advisor: kb.advisor,
      router,
      // Steps that need shared orientation/progress context consume the same
      // fresh projection as the shell. Passing it here keeps them from
      // rebuilding workflow or next-decision state locally.
      workflowProgress: currentWorkflowProgress(),
      // AUD-10's copy-groups path mutates `assays` in place via
      // store.setPath, so the assay-change re-render subscriber below never
      // fires for it and a workflowProgress snapshot taken once up front
      // would go stale; steps needing a post-mutation read call this instead.
      getWorkflowProgress: () => currentWorkflowProgress(),
      experience: loadOnboarding().experience,
      ...appController.actions,
      guidedStatus: appController.getGuidedState(),
      getGuidedStatus: () => appController.getGuidedState(),
      onStartGuided: () => guidedController.start(),
      onResumeGuided: () => guidedController.resume(),
      onRestartGuided: () => guidedController.restart(),
      onExplainGuided: explainGuided,
      kbIssueCount: kb.issues.length,
    });
  }

  router.onChange(renderActiveStep);
  renderActiveStep(router.current());

  // Every step's render() caches activeAssayId ONCE and documents that this
  // is only safe because the active assay never changes for the lifetime of
  // one render (see e.g. design.js's identical comment). The assay switcher
  // (shell.js) now makes that untrue, so switching assays must force a full
  // re-render of whichever step is on screen -- same as a route change,
  // because every closure inside render() (currentDesign(), prefill, etc.)
  // was built from the OLD assayId. Guarded on an actual change so ordinary
  // per-keystroke field edits (which also flow through this same
  // store.subscribe channel via the autosave one below) never trigger it.
  //
  // ALSO re-render when `assays` itself is a new array reference -- not just
  // when activeAssayId changes. Deleting a NON-active assay via the
  // switcher's "x" (shell.js's renderSwitcher) calls store.patch(result),
  // which replaces `assays` but leaves activeAssayId untouched, so the
  // activeAssayId check alone never fires; a step that lists every assay by
  // reading store.get().assays directly (study.js) then keeps showing the
  // deleted assay until some UNRELATED action happens to change
  // activeAssayId too. This is a real bug that shipped: verified live --
  // the switcher pill disappeared correctly (it has its own subscription)
  // while the Study step's own assay list kept a stale row for the assay
  // just removed. Safe as a reference check, not a deep one: core/store.js's
  // setPath MUTATES nested state in place (core/paths.js), so `assays` keeps
  // the SAME reference across ordinary per-keystroke field edits and only
  // gets a new one when store.patch() explicitly replaces it (add/remove
  // assay) -- this can never fire on a keystroke.
  let lastActiveAssayId = store.get().activeAssayId;
  let lastAssays = store.get().assays;
  store.subscribe((state) => {
    if (state.activeAssayId !== lastActiveAssayId || state.assays !== lastAssays) {
      lastActiveAssayId = state.activeAssayId;
      lastAssays = state.assays;
      renderActiveStep(router.current());
    }
  });

  // Split out of the debounced autosave subscriber that moved into
  // core/appController.js's startAutosave(): this push has no persistence
  // side effect at all, it is a pure view refresh, and it depends on
  // kb/conformance state (currentWorkflowProgress) that stays here rather
  // than being injected into appController.
  store.subscribe(() => {
    if (shell && typeof shell.setWorkflowProgress === 'function') {
      shell.setWorkflowProgress(currentWorkflowProgress());
    }
  });

  // Debounced: saving on every keystroke would fill the 5-slot ring buffer
  // with near-duplicate snapshots of the last few characters typed, rather
  // than the last 5 genuinely distinct states the ring buffer exists to
  // preserve as history. See core/appController.js's startAutosave/
  // flushAutosave for the mechanics.
  appController.startAutosave();

  // The one thing allowed to open itself on load, and only because the user
  // explicitly left a walkthrough paused mid-way on a previous visit.
  if (appController.getGuidedState().status === 'active') guidedController.resume();
}

init();
