// Two real, KB-backed assays whose only difference is Assay two's empty
// groups axis: with studyContext.comparisonMode 'groups', that empty axis is
// the ONE open decision keeping Assay two's `plan` off 'ready' (verified
// against the real engine while writing this test -- Assay two's headline
// starts {scope:'plan', status:'needs-decision'} and moves to
// {scope:'conformance', status:'needs-review'} the moment groups are filled
// in, with nothing else about the fixture changing).
function buildExperiment() {
  const experiment = emptyExperiment();
  const idA = experiment.assays[0].id;
  experiment.assays[0].label = 'Assay one';
  experiment.assays[0].readoutText = 'cell viability';
  experiment.assays[0].acquisition.modality = 'confocal';
  experiment.assays[0].design.groups.levels = ['CTL', 'TREATED'];
  experiment.assays[0].design.biologicalReplicates = 3;
  experiment.assays[0].design.technicalReplicates = 2;

  const idB = shortId();
  experiment.assays.push({
    ...JSON.parse(JSON.stringify(experiment.assays[0])),
    id: idB,
    label: 'Assay two',
    readoutText: 'migration',
    design: {
      groups: { levels: [] },
      factors: [],
      biologicalReplicates: 3,
      technicalReplicates: 2,
      idScheme: '',
      conditions: [],
    },
  });
  experiment.activeAssayId = idA;
  experiment.researchQuestion = 'does X affect Y';
  experiment.studyContext.comparisonMode = 'groups';
  return { experiment, idA, idB };
}

function progressFor(experiment, kb) {
  const conformance = checkConformance(experiment, kb, NAMING_CONFIG, BASE_TEMPLATE);
  return deriveWorkflowProgress(experiment, conformance, kb.questions);
}

// Mirrors main.js's own two options: a render-time `workflowProgress`
// snapshot plus a `getWorkflowProgress` the copy-groups path re-derives from.
function renderStudy(store, kb, overrides = {}) {
  const { document, install, restore } = createDomStub();
  install();
  const main = document.createElement('div');
  const toasts = [];
  const navigations = [];
  const router = { navigate: (id) => navigations.push(id) };
  studyStep.render(main, store, {
    showToast: (msg) => toasts.push(msg),
    router,
    workflowProgress: progressFor(store.get(), kb),
    getWorkflowProgress: () => progressFor(store.get(), kb),
    ...overrides,
  });
  return { main, toasts, navigations, restore };
}

function rows(main) {
  return main.querySelectorAll('.measurement-registry-row');
}

function rowLabelled(main, label) {
  return rows(main).find((row) => row.querySelector('.measurement-registry-open').textContent === label);
}

function findButton(main, text) {
  return main.querySelectorAll('button').find((button) => button.textContent === text);
}

test('a row badge\'s text and every data attribute derive from the same status record', () => {
  const { experiment } = buildExperiment();
  const kb = realKb();
  const store = createStore(experiment);
  const { main, restore } = renderStudy(store, kb);
  try {
    const progress = progressFor(store.get(), kb);
    const statusById = new Map(progress.assays.map((assay) => [assay.id, assay.status]));
    const allRows = rows(main);
    assert.equal(allRows.length, 2);

    for (const row of allRows) {
      const label = row.querySelector('.measurement-registry-open').textContent;
      const assay = store.get().assays.find((a) => a.label === label);
      const status = statusById.get(assay.id);

      const badge = row.querySelector('.measurement-status-badge');
      assert.equal(badge.dataset.scope, status.headline.scope);
      assert.equal(badge.dataset.status, status.headline.status);
      assert.equal(badge.dataset.tone, status.tone);
      assert.equal(badge.textContent, measurementStatusLabel(status.headline.scope, status.headline.status));

      const chips = row.querySelectorAll('.measurement-status-chip');
      const otherScopes = MEASUREMENT_STATUS_SCOPES.filter((scope) => scope !== status.headline.scope);
      assert.equal(chips.length, otherScopes.length);
      for (const chip of chips) {
        assert.ok(otherScopes.includes(chip.dataset.scope));
        assert.equal(chip.dataset.status, status[chip.dataset.scope]);
        assert.equal(chip.textContent, measurementStatusLabel(chip.dataset.scope, status[chip.dataset.scope]));
      }
    }
  } finally {
    restore();
  }
});

test('the status filter hides non-matching rows', () => {
  const { experiment } = buildExperiment();
  const kb = realKb();
  const store = createStore(experiment);
  const { main, restore } = renderStudy(store, kb);
  try {
    assert.equal(rows(main).length, 2);

    // Assay two's real, engine-verified headline before any mutation.
    const statusSelect = main.querySelectorAll('select')[0];
    statusSelect.value = 'plan:needs-decision';
    statusSelect.dispatch('change');

    const visible = rows(main);
    assert.equal(visible.length, 1);
    assert.equal(visible[0].querySelector('.measurement-registry-open').textContent, 'Assay two');

    // Switching back to 'all' restores both rows -- the filter is a pure
    // view of the same underlying rows, not a destructive one.
    statusSelect.value = 'all';
    statusSelect.dispatch('change');
    assert.equal(rows(main).length, 2);
  } finally {
    restore();
  }
});

