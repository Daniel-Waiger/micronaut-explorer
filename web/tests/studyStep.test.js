test('copy-groups mutates `assays` IN PLACE, yet the badges still reflect the new state', () => {
  const { experiment } = buildExperiment();
  const kb = realKb();
  const store = createStore(experiment);
  const { main, restore } = renderStudy(store, kb);
  try {
    const beforeAssaysRef = store.get().assays;

    const rowBefore = rowLabelled(main, 'Assay two');
    const badgeBefore = rowBefore.querySelector('.measurement-status-badge');
    // Assay two starts with no groups while the study requires them --
    // 'plan' is the first axis not at its best, so it is the headline.
    assert.equal(badgeBefore.dataset.scope, 'plan');
    assert.equal(badgeBefore.dataset.status, 'needs-decision');

    const applyBtn = findButton(main, 'Copy groups to measurements that have none');
    assert.ok(applyBtn);
    applyBtn.click();

    // store.setPath mutates `assays` IN PLACE (core/store.js) -- this is
    // the exact condition under which main.js:497-501's `assays !==
    // lastAssays` re-render subscriber does NOT fire, so this step must
    // have refreshed its own progress snapshot to show the change at all.
    assert.equal(store.get().assays, beforeAssaysRef);

    const rowAfter = rowLabelled(main, 'Assay two');
    const badgeAfter = rowAfter.querySelector('.measurement-status-badge');
    // Groups are filled in now, so 'plan' reaches its best status and the
    // headline moves on to the next axis not yet at its best.
    assert.equal(badgeAfter.dataset.scope, 'conformance');
    assert.equal(badgeAfter.dataset.status, 'needs-review');
  } finally {
    restore();
  }
});

